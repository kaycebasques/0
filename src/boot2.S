/* ============================================================================
 * RP2040 BOOT STAGE 2 SECTOR (.boot2)
 * ============================================================================
 *
 * EMBEDDED CONCEPTS FOR SOFTWARE ENGINEERS:
 *
 * Why a Separate Assembly (.S) File?
 * In C, global `const uint8_t data[]` arrays are placed in read-only data sections
 * marked with section flag "a" (Allocatable). However, ARM Cortex-M processors and
 * hardware emulators (like Wokwi) enforce Memory Protection Unit (MPU) execution
 * rules. Memory segments marked without the "x" (Executable) flag will trigger a
 * hardware fault if the CPU attempts to fetch instructions from them.
 *
 * By declaring `.section .boot2, "ax"`, we instruct GNU as / LLVM mc to flag this
 * 256-byte sector as both Allocatable ("a") and EXECUTABLE ("x").
 *
 * Bootloader Functionality:
 * This 256-byte binary payload is the official Winbond W25Q080 SPI Flash Boot Stage 2
 * driver from the Raspberry Pi Pico SDK. Upon power-on, the RP2040 internal ROM
 * bootloader reads this sector to:
 *   1. Configure the Synchronous Serial Interface (SSI) QSPI Flash controller
 *      into high-speed 0x03 Execute-In-Place (XIP) continuous read mode.
 *   2. Set Vector Table Offset Register (VTOR = 0x10000100).
 *   3. Jump to Reset_Handler at 0x100001c4.
 *
 * Offset 0xfc (bytes 252..255) contains the required 32-bit CRC32-MPEG2 checksum
 * (0x7a4eb274 in little-endian: 0x74, 0xb2, 0x4e, 0x7a).
 *
 * [source: docs/rp2040.pdf "2.8.1.3 Flash Second Stage"]
 * [source: docs/rp2040.pdf "2.8.1.3.1 Checksum"]
 * [source: docs/hw.pdf "2.8 Flash Selection"]
 * [source: examples/pico-sdk/src/rp2040/boot_stage2/boot2_w25q080.S]
 * [source: examples/pico-sdk/src/rp2040/pico_platform/script_include/section_boot2.incl]
 */

